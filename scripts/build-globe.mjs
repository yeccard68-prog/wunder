// The globe for the "Blick ins Innere" drawing of the Earth (components/viz/reveal): the land of Natural Earth
// (public domain, via the world-atlas package, 110m) seen from space above Africa and Europe, as one SVG path in a
// circle of radius 100 around (0, 0). Land on the far side is pressed onto the rim, so coasts that cross the horizon
// run along it.   node scripts/build-globe.mjs  → components/viz/reveal/globe.ts
import fs from "node:fs";
import { feature } from "topojson-client";

const LON0 = 12, LAT0 = 18; // the point straight below the viewer
const R = 100;
const rad = Math.PI / 180;
const topo = JSON.parse(fs.readFileSync("node_modules/world-atlas/land-110m.json", "utf8"));
const land = feature(topo, topo.objects.land);

const project = ([lon, lat]) => {
  const l = (lon - LON0) * rad, p = lat * rad, p0 = LAT0 * rad;
  const x = R * Math.cos(p) * Math.sin(l);
  const y = -R * (Math.cos(p0) * Math.sin(p) - Math.sin(p0) * Math.cos(p) * Math.cos(l));
  const front = Math.sin(p0) * Math.sin(p) + Math.cos(p0) * Math.cos(p) * Math.cos(l) >= 0;
  if (front) return [x, y, true];
  const d = Math.hypot(x, y) || 1; // far side: onto the rim, in the same direction
  return [(x / d) * R, (y / d) * R, false];
};

const rings = land.features.flatMap((f) => (f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates)).flat();
let d = "";
for (const ring of rings) {
  const pts = ring.map(project);
  if (!pts.some((p) => p[2])) continue; // entirely on the far side
  d += "M" + pts.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join("L") + "Z";
}
fs.mkdirSync("components/viz/reveal", { recursive: true });
fs.writeFileSync("components/viz/reveal/globe.ts",
  `// Generated by scripts/build-globe.mjs – land of Natural Earth (public domain), seen above ${LAT0}° N ${LON0}° E, radius ${R}.\nexport const LAND = "${d}";\n`);
console.log(`globe: ${d.length} characters`);
